HANGUL = {k: v.split("/") for k, v in _HANGUL.items()}
HANGUL_H = 10


def hangul_bits(ch: str) -> set:
    rows = HANGUL[ch]
    top = (HANGUL_H - len(rows)) // 2
    return {(gx, top + gy) for gy, row in enumerate(rows) for gx, b in enumerate(row) if b == "#"}
