SMALL = {k: v.split("/") for k, v in _SMALL.items()}


def text_width(text: str) -> int:
    return sum(len(SMALL[ch][0]) + 1 for ch in text.upper()) - 1


def draw_text(c: Canvas, x: int, y: int, text: str, colour, shadow=None) -> int:
    cx = x
    for ch in text.upper():
        rows = SMALL[ch]
        for gy, row in enumerate(rows):
            for gx, bit in enumerate(row):
                if bit == "#":
                    if shadow is not None:
                        c.put(cx + gx + 1, y + gy + 1, shadow)
                    c.put(cx + gx, y + gy, colour)
        cx += len(rows[0]) + 1
    return cx - x - 1


def text_bits(text: str) -> set:
    bits, cx = set(), 0
    for ch in text.upper():
        rows = SMALL[ch]
        for gy, row in enumerate(rows):
            for gx, bit in enumerate(row):
                if bit == "#":
                    bits.add((cx + gx, gy))
        cx += len(rows[0]) + 1
    return bits


# --- 7px title font -------------------------------------------------------------
_TITLE = {
    "A": ".###./#...#/#...#/#####/#...#/#...#/#...#",
    "H": "#...#/#...#/#...#/#####/#...#/#...#/#...#",
    "I": "###/.#./.#./.#./.#./.#./###",
    "M": "#...#/##.##/#.#.#/#.#.#/#...#/#...#/#...#",
    "R": "####./#...#/#...#/####./#.#../#..#./#...#",
    "T": "#####/..#../..#../..#../..#../..#../..#..",
    "U": "#...#/#...#/#...#/#...#/#...#/#...#/.###.",
    ",": "../../../../../.#/#.",
    "'": "#/#/./././././",
    " ": "../../../../../../..",
}
TITLE = {k: v.split("/") for k, v in _TITLE.items()}


def title_strokes(text: str) -> tuple[list[set], int]:
    """Per-glyph sets of 7px-font cells (no scaling) and the total advance."""
    glyphs, cx = [], 0
    for ch in text.upper():
        rows = TITLE[ch]
        cells = {(cx + gx, gy) for gy, row in enumerate(rows) for gx, b in enumerate(row) if b == "#"}
        glyphs.append(cells)
        cx += len(rows[0]) + 1
    return glyphs, cx - 1


